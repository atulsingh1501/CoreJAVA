package CoreJava;

public class o14_forLoop {
        public static void main(String[] args) throws InterruptedException {

            for(int i = 5; i >= 0; i--) {
                System.out.println(i);
                Thread.sleep(1000); // 1 second
            }
            System.out.println("HAPPY NEW YEAR!!❤️❤️");
        }
    }

