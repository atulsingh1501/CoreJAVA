package OOPs.MethodOverriding;

public class Animal {

    // Method Overriding: Method overriding occurs when a subclass (child class) provides its own implementation of a method
    // that is already defined in its parent class.
    void Speak(){
        System.out.println("This Animal Speak");
    }
    void Move(){
        System.out.println( "This animal is running");
    }
}
